export const allCharacters = versionGroups.flatMap((group) =>
  group.characters.map((character) => ({
    ...character,
    version: group.version,
    versionTitleZh: group.titleZh,
    versionTitleEn: group.titleEn,
    versionReleaseDate: group.releaseDate,
  })),
);

export function findCharacterBySlug(slug) {
  return allCharacters.find((character) => character.slug === slug);
}

export function findGroupByCharacterSlug(slug) {
  return versionGroups.find((group) =>
    group.characters.some((character) => character.slug === slug),
  );
}

export function findGroupByVersion(version) {
  return versionGroups.find((group) => group.version === version);
}

export function findFeaturedCharacterByVersion(version) {
  const group = findGroupByVersion(version);

  if (!group) {
    return undefined;
  }

  return (
    group.characters.find((character) => character.slug === group.featuredCharacterSlug) ??
    group.characters[0]
  );
}
